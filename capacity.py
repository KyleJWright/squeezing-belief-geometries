"""How does a model share its residual stream between several belief geometries?

Example:
    python capacity.py --ckpt runs/seed0/parallel_K2_d4.pt --out results/seed0/caps/parallel_K2_d4_cap

For a model trained on a mixture or parallel composite (see composite.py), on freshly sampled
sequences with exact beliefs, this reports at every residual layer index (0..n_layers):

  r2[k]       Held-out R^2 of a ridge decoder from activations to process k's belief.
              (Concatenating all layers is reported as layer "concat".)
  overlap     K x K matrix of subspace overlaps. Each process k gets a 2-dim subspace Q_k: the
              directions along which the activation moves as process k's belief moves, from the
              generative fit  activation ~ sum_k M_k u_k + m, with u_k = process k's belief in
              2 tangent coordinates of its simplex. overlap[i, j] = ||Q_i^T Q_j||_F^2 / 2, which is
              0 for orthogonal planes and 1 for identical planes (mean of cos^2 of principal angles).
              Measured in the READABLE space: every LayerNorm subtracts the mean of the d coordinates,
              so the model cannot see the all-ones direction. The planes are projected onto the
              (d-1)-dimensional hyperplane orthogonal to it before measuring. (overlap_raw: in R^d.)
  overlap_gamma  Final layer only: the same overlap in the metric the output head's LayerNorm
              imposes, <x, y> = x^T diag(gamma)^2 y on that hyperplane (gamma = its learned scale).
              Euclidean angles are a convention; if conclusions hold in both metrics, they do not
              depend on that choice.
  overlap_logit, plane_agreement, gen_r2_logit
              The same planes fitted with each process's optimal next-token logits log(eta N)
              (centred) as coordinates instead of its belief eta. The two are related by a smooth
              nonlinear map of the triangle, so a curved patch lying in a fixed plane gives the same
              plane both ways: plane_agreement[k] = overlap of the two fits of process k (1 = same plane).
  offset_sep  Mixture regime only: distance between two processes' mean activations (in the
              readable space), divided by the processes' typical within-process spread. Large
              values mean two processes can share directions yet sit apart, told apart by position.
  mean_overlap_kept  Mean overlap over processes the layer represents (R^2 >= 0.5). A process the
              model has dropped still gets a fitted plane, but it is noise; exclude it.
  bound       The least possible mean pairwise overlap for K planes of dim 2 in R^n with n = d - 1,
              the readable space (a frame bound): sum over i != j of ||Q_i^T Q_j||^2 >= D^2/n - D
              with D = 2K, i.e. mean overlap >= max(0, (2K/n - 1) / (K - 1)).
  gen_r2      Fraction of activation variance explained by the beliefs (generative fit).
  eff_dim     Participation ratio of the activation covariance: (sum lambda)^2 / sum lambda^2.

Mixture regime: process k's maps are fitted on sequences generated by k (its belief is undefined
elsewhere). Parallel regime: all K beliefs are fitted jointly on every sequence.
"""

import argparse
import json

import numpy as np
import torch

from fitting import choose_ridge, fit_affine
from composite import build
from model import load_checkpoint

R2_KEEP = 0.5  # a process counts as represented at a layer if its belief decodes with R^2 >= this

# Orthonormal basis of the sum-zero plane in R^3: tangent coordinates of the 2-simplex.
E = np.linalg.qr(np.array([[1.0, -1.0, 0.0], [1.0, 1.0, -2.0]]).T)[0]  # (3, 2)


def r2_score(Y, Yhat):
    ss_res = ((Y - Yhat) ** 2).sum(0)
    ss_tot = ((Y - Y.mean(0)) ** 2).sum(0)
    keep = ss_tot > 1e-12
    return float(1 - ss_res[keep].sum() / ss_tot[keep].sum())


def orth(M):
    U, s, _ = np.linalg.svd(M, full_matrices=False)
    return U[:, s > 1e-8 * max(s.max(), 1e-30)]


def readable(d):
    """Projector onto the hyperplane orthogonal to the all-ones direction, which LayerNorm removes."""
    return np.eye(d) - np.ones((d, d)) / d


def overlap_matrix(Qs):
    K = len(Qs)
    O = np.eye(K)
    for i in range(K):
        for j in range(K):
            if i != j:
                O[i, j] = float(np.linalg.norm(Qs[i].T @ Qs[j]) ** 2 / max(min(Qs[i].shape[1], Qs[j].shape[1]), 1))
    return O


def frame_bound(K, d, dim=2):
    """Least mean pairwise overlap (normalised by dim) for K subspaces of dimension dim in R^d.

    With P = sum_k P_k (orthogonal projectors), tr P = D = K*dim and rank P <= d, so
    ||P||_F^2 >= D^2/d. Expanding, sum_{i != j} ||Q_i^T Q_j||_F^2 >= D^2/d - D. Dividing by
    K(K-1) ordered pairs and by dim gives the bound below.
    """
    if K < 2:
        return 0.0
    D = K * dim
    return max(0.0, (D * D / d - D) / (K * (K - 1) * dim))


def collect_resid(model, tokens, batch=2048):
    out = None
    with torch.no_grad():
        for i in range(0, len(tokens), batch):
            _, rs = model(torch.from_numpy(tokens[i:i + batch]), return_resid=True)
            rs = [r.numpy() for r in rs]
            out = [[r] for r in rs] if out is None else [o + [r] for o, r in zip(out, rs)]
    return [np.concatenate(o) for o in out]  # list over layers of (N, L, d)


def belief_coords(B, k, comp):
    """Process k's belief in 2 tangent coordinates of its simplex."""
    return (B - 1 / 3) @ E


def logit_coords(B, k, comp):
    """Process k's optimal next-token logits, log(eta N), centred, in the same 2 tangent coordinates."""
    logp = np.log(np.clip(comp.components[k].next_token_probs(B), 1e-12, 1))
    return (logp - logp.mean(-1, keepdims=True)) @ E


def generative_maps(A_seq, beliefs, comp, coords):
    """Fit activation ~ m + sum_k M_k u_k with u_k = coords(process k's belief); return [M_k], R^2.

    Parallel regime: all processes jointly on every sequence. Mixture: each process on its own sequences.
    """
    d = A_seq.shape[-1]
    if comp.regime == "parallel":
        A = A_seq.reshape(-1, d)
        U = np.concatenate([coords(B.reshape(-1, 3), k, comp) for k, (B, _) in enumerate(beliefs)], axis=1)
        M, m = fit_affine(U, A, ridge=1e-8)  # M: (d, 2K)
        return [M[:, 2 * k:2 * k + 2] for k in range(comp.K)], r2_score(A, U @ M.T + m)
    Ms, gen = [], []
    for k, (B, mask) in enumerate(beliefs):
        A = A_seq[mask].reshape(-1, d)
        U = coords(B[mask].reshape(-1, 3), k, comp)
        M, m = fit_affine(U, A, ridge=1e-8)
        gen.append(r2_score(A, U @ M.T + m))
        Ms.append(M)
    return Ms, float(np.mean(gen))


def analyse_layer(A_seq, beliefs, comp, rng, half, gamma=None):
    """A_seq: (N, L, d). beliefs: list of (B (N, L, 3), mask (N,)).

    gamma: the scale vector of the LayerNorm that reads this layer (given for the final layer: the
    output head's LayerNorm). If given, overlaps are also measured in the metric x^T diag(gamma)^2 y on
    the readable space, i.e. after the LayerNorm's per-coordinate scaling (overlap_gamma).
    """
    K = comp.K
    res = {"r2": [], "gen_r2": None}
    # Decoders: activation -> belief of process k (held-out R^2 on the second half of sequences).
    for B, mask in beliefs:
        tr = mask & half
        te = mask & ~half
        Atr, Ytr = A_seq[tr].reshape(-1, A_seq.shape[-1]), B[tr].reshape(-1, 3)
        Ate, Yte = A_seq[te].reshape(-1, A_seq.shape[-1]), B[te].reshape(-1, 3)
        ridge = choose_ridge(Atr, Ytr, rng)
        W, c = fit_affine(Atr, Ytr, ridge)
        res["r2"].append(r2_score(Yte, Ate @ W.T + c))
    # Generative maps -> one 2-dim subspace per process.
    d = A_seq.shape[-1]
    P = readable(d)
    Ms, gen_r2 = generative_maps(A_seq, beliefs, comp, belief_coords)
    res["gen_r2"] = gen_r2
    Qs = [orth(P @ Mk) for Mk in Ms]
    Qs_raw = [orth(Mk) for Mk in Ms]
    # The same fit with each process's optimal next-token LOGITS as coordinates, log(eta N) centred,
    # instead of its belief eta. The softmax makes logits, not probabilities, the natural linear
    # target; the two coordinate systems are related by a smooth nonlinear map of the triangle.
    # If the residual stream holds a curved patch inside a fixed plane, both fits find that plane.
    Ms_logit, res["gen_r2_logit"] = generative_maps(A_seq, beliefs, comp, logit_coords)
    Qs_logit = [orth(P @ Mk) for Mk in Ms_logit]
    res["overlap_logit"] = overlap_matrix(Qs_logit).tolist()
    res["plane_agreement"] = [float(np.linalg.norm(a.T @ b) ** 2 / 2) for a, b in zip(Qs, Qs_logit)]
    if comp.regime == "mixture":
        means, spreads = [], []
        for B, mask in beliefs:
            Ar = A_seq[mask].reshape(-1, d) @ P
            means.append(Ar.mean(0))
            spreads.append(np.sqrt(((Ar - Ar.mean(0)) ** 2).sum(1).mean()))
        scale = float(np.mean(spreads))
        res["offset_sep"] = [[float(np.linalg.norm(means[i] - means[j]) / max(scale, 1e-12)) for j in range(K)]
                             for i in range(K)]
    O = overlap_matrix(Qs)
    res["overlap"] = O.tolist()
    res["overlap_raw"] = overlap_matrix(Qs_raw).tolist()
    if gamma is not None:
        G = np.diag(np.asarray(gamma, dtype=float))
        res["overlap_gamma"] = overlap_matrix([orth(G @ P @ Mk) for Mk in Ms]).tolist()
    res["mean_overlap"] = float(O[~np.eye(K, dtype=bool)].mean()) if K > 1 else 0.0
    # Overlap among processes the layer actually represents: a dropped process's fitted plane is noise.
    kept = [k for k in range(K) if res["r2"][k] >= R2_KEEP]
    pairs = [(i, j) for i in kept for j in kept if i != j]
    res["kept"] = kept
    res["mean_overlap_kept"] = float(np.mean([O[i, j] for i, j in pairs])) if pairs else float("nan")
    if gamma is not None:
        Og = np.array(res["overlap_gamma"])
        res["mean_overlap_gamma_kept"] = float(np.mean([Og[i, j] for i, j in pairs])) if pairs else float("nan")
    C = np.cov(A_seq.reshape(-1, d).T)
    lam = np.clip(np.linalg.eigvalsh(C), 0, None)
    res["eff_dim"] = float(lam.sum() ** 2 / max((lam ** 2).sum(), 1e-30))
    return res


def model_loss(model, comp, tokens):
    with torch.no_grad():
        logits = model(torch.from_numpy(tokens[:, :-1]))
        return float(torch.nn.functional.cross_entropy(
            logits.reshape(-1, comp.d_vocab), torch.from_numpy(tokens[:, 1:]).reshape(-1)))


def optimal_loss_on(comp, tokens):
    """Bayes-optimal cross-entropy on the SAME sequences the model is scored on. Comparing on shared
    samples cancels most sampling noise, so the loss ratio is not pushed below 1 by chance."""
    P = comp.next_token_dist(tokens[:, :-1])
    p = np.take_along_axis(P, tokens[:, 1:, None], axis=-1)[..., 0]
    return float(-np.log(np.clip(p, 1e-300, 1)).mean())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--n_seq", type=int, default=6000)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)

    model, ckpt = load_checkpoint(args.ckpt)
    spec = ckpt["extra"]["spec"]
    comp = build(spec)
    d, L = model.cfg.d_model, model.cfg.n_ctx

    tokens, labels = comp.sample(args.n_seq, L + 1, rng)
    opt = optimal_loss_on(comp, tokens)
    loss = model_loss(model, comp, tokens)
    inputs = tokens[:, :-1]
    beliefs = comp.factor_beliefs(inputs, labels)
    resid = collect_resid(model, inputs)
    half = rng.random(len(inputs)) < 0.5

    layers = {}
    for l, A in enumerate(resid):
        gamma = model.ln_final.weight.detach().numpy() if l == len(resid) - 1 else None
        layers[str(l)] = analyse_layer(A, beliefs, comp, rng, half, gamma)
    layers["concat"] = {"r2": analyse_layer(np.concatenate(resid, -1), beliefs, comp, rng, half)["r2"]}

    summary = {"name": comp.name, "regime": comp.regime, "vocab": comp.vocab, "K": comp.K, "d_model": d,
               "step": ckpt["extra"].get("step"), "loss": loss, "optimal_loss": opt, "loss_ratio": loss / opt,
               "frame_bound": frame_bound(comp.K, d - 1), "layers": layers}
    with open(args.out + ".json", "w") as f:
        json.dump(summary, f, indent=1)

    print(f"{comp.name}, d_model {d}, step {summary['step']}: loss ratio {loss / opt:.4f}, "
          f"frame bound on mean overlap {summary['frame_bound']:.3f}")
    print(f"{'layer':>7} {'R2 per process':>24} {'mean overlap':>13} {'(kept only)':>12} {'gen R2':>7} {'eff dim':>8}")
    for name, r in layers.items():
        r2 = " ".join(f"{v:.3f}" for v in r["r2"])
        if name == "concat":
            print(f"{name:>7} {r2:>24}")
        else:
            print(f"{name:>7} {r2:>24} {r['mean_overlap']:>13.3f} {r['mean_overlap_kept']:>12.3f} "
                  f"{r['gen_r2']:>7.3f} {r['eff_dim']:>8.2f}")
    print(f"saved {args.out}.json")


if __name__ == "__main__":
    main()
