"""Several Mess3 processes in one model: the sparse and dense regimes.

    mixture  (sparse)  Each sequence comes from ONE of K processes. Only one belief geometry is
                       "active" per sequence, the analogue of sparse features in Elhage et al.
                       vocab="disjoint": process k uses its own 3 tokens (3k, 3k+1, 3k+2), so the
                       first token reveals the process. vocab="shared": all use tokens 0-2, so the
                       model must also infer which process it is in (non-ergodic, in-context).
    parallel (dense)   K independent processes run side by side; each observed token is the tuple of
                       their K sub-tokens (vocab 3^K). Every belief is active at every position.
                       This is the factored setting of Shai et al. (2026).

Each process's belief lives on a 2-simplex, so a factored representation needs 2K residual
dimensions for the beliefs (plus whatever the model uses for anything else). This project uses K = 2.

A "spec" is a plain dict, saved in checkpoints, from which build(spec) rebuilds the composite:
    {"regime": "mixture" | "parallel", "vocab": "disjoint" | "shared",
     "params": [[x, alpha], ...], "weights": [...] (mixture only)}
"""

import numpy as np

from processes import mess3

# Distinct, valid Mess3 parameters (x < 0.5, 1/3 < alpha < 1), so processes are distinguishable.
MESS3_VARIANTS = [(0.05, 0.85), (0.15, 0.60), (0.10, 0.75), (0.20, 0.90), (0.08, 0.65), (0.12, 0.95)]


def default_spec(regime, K, vocab="disjoint"):
    spec = {"regime": regime, "vocab": vocab, "params": [list(p) for p in MESS3_VARIANTS[:K]]}
    if regime == "mixture":
        spec["weights"] = [1.0 / K] * K
    return spec


def build(spec):
    return Composite(spec)


class Composite:
    def __init__(self, spec):
        self.spec = spec
        self.regime = spec["regime"]
        self.vocab = spec.get("vocab", "disjoint")
        self.components = [mess3(x, a, name=f"mess3(x={x},a={a})") for x, a in spec["params"]]
        self.K = len(self.components)
        self.S = [c.S for c in self.components]
        if self.regime == "mixture":
            self.weights = np.asarray(spec.get("weights", [1.0 / self.K] * self.K), dtype=float)
            self.d_vocab = 3 * self.K if self.vocab == "disjoint" else 3
        elif self.regime == "parallel":
            self.d_vocab = 3 ** self.K
        else:
            raise ValueError(self.regime)
        self.name = f"{self.regime}-K{self.K}" + (f"-{self.vocab}" if self.regime == "mixture" else "")

    @property
    def belief_dims(self):
        """Dimension of each process's belief simplex (S_k - 1)."""
        return [s - 1 for s in self.S]

    # ------------------------------------------------------------------ token maps
    def encode_parallel(self, sub):
        """sub: (K, N, L) sub-tokens -> (N, L) joint tokens (first process = most significant)."""
        return np.ravel_multi_index(tuple(sub), (3,) * self.K)

    def decode_parallel(self, tokens):
        return np.stack(np.unravel_index(tokens, (3,) * self.K))  # (K, N, L)

    # ------------------------------------------------------------------ sampling
    def sample(self, n, length, rng, only=None):
        """Return (tokens (n, length), labels (n,)).

        mixture: labels = which process generated each sequence (only=k forces process k).
        parallel: labels are all -1.
        """
        if self.regime == "mixture":
            labels = np.full(n, only) if only is not None else rng.choice(self.K, size=n, p=self.weights)
            tokens = np.empty((n, length), dtype=np.int64)
            for k in range(self.K):
                idx = np.where(labels == k)[0]
                if len(idx):
                    sub = self.components[k].sample(len(idx), length, rng)
                    tokens[idx] = sub + (3 * k if self.vocab == "disjoint" else 0)
            return tokens, labels
        sub = np.stack([c.sample(n, length, rng) for c in self.components])
        return self.encode_parallel(sub), np.full(n, -1)

    # ------------------------------------------------------------------ beliefs
    def sub_tokens(self, tokens, k):
        """Process k's own tokens (0-2) for every sequence (mixture: only meaningful where label == k)."""
        if self.regime == "parallel":
            return self.decode_parallel(tokens)[k]
        return tokens - 3 * k if self.vocab == "disjoint" else tokens

    def factor_beliefs(self, tokens, labels):
        """Exact belief of each process after each prefix.

        Returns a list over k of (beliefs (N, L, 3), mask (N,)): mask marks the sequences for which
        process k's belief is defined (mixture: generated by k; parallel: all).
        """
        out = []
        for k, comp in enumerate(self.components):
            mask = np.ones(len(tokens), bool) if self.regime == "parallel" else labels == k
            B = np.zeros(tokens.shape + (3,))
            if mask.any():
                B[mask] = comp.beliefs_along(self.sub_tokens(tokens[mask], k))[0]
            out.append((B, mask))
        return out

    def next_token_dist(self, tokens):
        """Bayes-optimal next-token distribution after each prefix: (N, L, d_vocab)."""
        N, L = tokens.shape
        if self.regime == "parallel":
            sub = self.decode_parallel(tokens)
            P = np.ones((N, L, 1))
            for k, comp in enumerate(self.components):
                B, _ = comp.beliefs_along(sub[k])
                pk = np.einsum("nls,xsr->nlx", B, comp.T)  # (N, L, 3)
                P = (P[..., :, None] * pk[..., None, :]).reshape(N, L, -1)
            return P
        # Mixture: posterior over processes times each process's prediction.
        P = np.zeros((N, L, self.d_vocab))
        post, preds = self._posterior_and_preds(tokens)
        for k in range(self.K):
            off = 3 * k if self.vocab == "disjoint" else 0
            P[..., off:off + 3] += post[..., k:k + 1] * preds[k]
        return P

    def _posterior_and_preds(self, tokens):
        logpost = np.zeros(tokens.shape + (self.K,))
        preds = []
        for k, comp in enumerate(self.components):
            sub = self.sub_tokens(tokens, k)
            valid = (sub >= 0) & (sub < 3)
            sub_c = np.where(valid, sub, 0)
            B, prob = comp.beliefs_along(sub_c)
            ok = np.cumprod(valid, axis=1).astype(bool)
            prob = np.where(ok, prob, 0.0)
            logpost[..., k] = np.log(self.weights[k]) + np.log(np.maximum(prob, 1e-300))
            preds.append(np.einsum("nls,xsr->nlx", B, comp.T))
        post = np.exp(logpost - logpost.max(-1, keepdims=True))
        post /= post.sum(-1, keepdims=True)
        return post, preds

    def process_posterior(self, tokens):
        """Mixture only: exact posterior probability of each process after each prefix, (N, L, K)."""
        if self.regime != "mixture":
            raise ValueError("the process posterior is only defined for the mixture regime")
        return self._posterior_and_preds(tokens)[0]

    def optimal_loss(self, n_ctx, rng=None, n=20000):
        """Bayes-optimal cross-entropy, nats per token (exact for parallel, Monte Carlo for mixture)."""
        if self.regime == "parallel":
            return float(sum(c.optimal_loss(n_ctx) for c in self.components))
        rng = rng or np.random.default_rng(12345)
        tokens, _ = self.sample(n, n_ctx, rng)
        P = np.clip(self.next_token_dist(tokens), 1e-300, 1)
        return float(-(P * np.log(P)).sum(-1).mean())
